// Creates the local secret files for `wrangler dev`, never printing a value:
//   .dev.vars              (from .dev.vars.example, with a fresh TOKEN_ENC_KEY)
//   fake-google/.dev.vars  (fresh FAKE_ADMIN_TOKEN, FAKE_SIGNING_KEY, FAKE_LOGIN_SECRET)
// Both are gitignored and written with mode 600. Existing values are kept; only missing or placeholder keys are
// generated, so re-running never invalidates local tokens sealed with the current key. Keys are 32 bytes from
// crypto.getRandomValues, base64. The repository's .env is not touched.
//
// Usage: npx tsx scripts/dev-secrets.ts
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MAIN_VARS = path.join(ROOT, ".dev.vars");
const MAIN_EXAMPLE = path.join(ROOT, ".dev.vars.example");
const FAKE_VARS = path.join(ROOT, "fake-google", ".dev.vars");

export function generateKey(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(32));
  return Buffer.from(bytes).toString("base64");
}

/** A value that still needs generating: absent, empty, or a `<...>` placeholder. */
function needsValue(value: string | undefined): boolean {
  return value === undefined || value.trim() === "" || /^<.*>$/.test(value.trim());
}

const LINE = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/;

/**
 * Sets each of `keys` that needs a value in dotenv `text`, in place where the key already appears (keeping
 * comments and order), else appended. Returns the new text and which keys were generated.
 */
export function fillKeys(text: string, keys: readonly string[]): { text: string; generated: string[] } {
  const lines = text === "" ? [] : text.replace(/\n$/, "").split("\n");
  const generated: string[] = [];
  const seen = new Set<string>();
  const out = lines.map((line) => {
    const m = LINE.exec(line);
    const key = m?.[1];
    if (!key || !keys.includes(key)) return line;
    seen.add(key);
    if (!needsValue(m[2])) return line;
    generated.push(key);
    return `${key}=${generateKey()}`;
  });
  for (const key of keys) {
    if (seen.has(key)) continue;
    generated.push(key);
    out.push(`${key}=${generateKey()}`);
  }
  return { text: `${out.join("\n")}\n`, generated };
}

function writeSecretFile(file: string, base: string, keys: readonly string[]): void {
  const existed = existsSync(file);
  const { text, generated } = fillKeys(existed ? readFileSync(file, "utf8") : base, keys);
  writeFileSync(file, text, { mode: 0o600 });
  // writeFileSync's mode applies only when it creates the file.
  chmodSync(file, 0o600);
  const rel = path.relative(ROOT, file);
  for (const key of keys) console.log(`dev-secrets: ${rel} ${key} ${generated.includes(key) ? "generated" : "kept"}`);
  if (!existed) console.log(`dev-secrets: ${rel} created (mode 600)`);
}

function main(): void {
  writeSecretFile(MAIN_VARS, readFileSync(MAIN_EXAMPLE, "utf8"), ["TOKEN_ENC_KEY"]);
  writeSecretFile(FAKE_VARS, "# Local secrets of the fake Google Worker (generated by scripts/dev-secrets.ts). Never commit.\n", [
    "FAKE_ADMIN_TOKEN",
    "FAKE_SIGNING_KEY",
    "FAKE_LOGIN_SECRET",
  ]);
  console.log("dev-secrets: .env not touched (deployed secrets are set by the deploy step)");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
