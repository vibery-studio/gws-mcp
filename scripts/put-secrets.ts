// Sets Worker secrets from the repository's .env without any value entering argv, logs or output.
//
// Reads the dotenv file by path, generates the deployment keys that are absent (32 random bytes, base64) and
// appends them (mode 600; without `--rotate` existing lines are never rewritten), then runs `wrangler secret put
// <NAME> --name <worker> --config <worker's wrangler config>` once per name with the value written to stdin. The config pins
// the Cloudflare account. Output is key names plus success or failure only; a failing wrangler's error output
// is shown with every loaded value scrubbed. The Google client credentials are never generated: when one is
// missing the run stops (exit 2) before writing or uploading anything.
//
// TOKEN_ENC_KEY encrypts every stored Google token, so replacing the deployed one makes them all unreadable.
// Before setting it, the run lists the Worker's secret names (`wrangler secret list`, names only) and stops
// (exit 2, nothing written or uploaded) when it is already deployed, unless `--rotate` is passed.
// With `--rotate`, each requested rotate-only key (TOKEN_ENC_KEY) gets a freshly generated value that replaces
// its line(s) in the env file in place (exactly one line remains, appended when absent; every other line is kept
// byte for byte; mode 600), and that new value is uploaded. Other names are never regenerated by `--rotate`.
//
// Each Worker's config is the operator's local one (scripts/wrangler.ts CONFIGS), never a tracked example: wrangler.jsonc,
// wrangler.e2e.jsonc, fake-google/wrangler.jsonc.
//
// The fake-mode E2E Worker `gws-mcp-e2e` (wrangler.e2e.jsonc) takes its TOKEN_ENC_KEY from the env key
// E2E_TOKEN_ENC_KEY (generated when absent, same rotate-only guard), never from TOKEN_ENC_KEY, and its Google client
// pair is the fixed fake placeholder: the env file's Google values are never read for it.
//
// Usage: npx tsx scripts/put-secrets.ts --worker <gws-mcp|gws-mcp-e2e|gws-mcp-fake-google> --names A,B [--env-file <path>] [--rotate]
//   --rotate  generate a new TOKEN_ENC_KEY (when named), replace it in the env file and upload it over the deployed one
import { type ChildProcess, type SpawnOptions, spawn as nodeSpawn } from "node:child_process";
import { appendFileSync, chmodSync, existsSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FAKE_CLIENT_ID, FAKE_CLIENT_SECRET } from "../src/config";
import { CONFIGS } from "./wrangler";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Where a secret's value comes from: an env-file key, or a fixed non-secret value that never touches the file. */
type Source = { readonly envKey: string } | { readonly fixed: string };

interface WorkerTarget {
  /** Wrangler config, relative to the repository root; it pins the account. */
  config: string;
  names: readonly string[];
  /** Per secret name; a name without an entry reads the env key of the same name. */
  sources?: Readonly<Record<string, Source>>;
}

/** The only Workers this script may touch, their wrangler config (which pins the account) and secret names. */
const WORKERS: Readonly<Record<string, WorkerTarget>> = {
  "gws-mcp": { config: CONFIGS.main.local, names: ["TOKEN_ENC_KEY", "GOOGLE_CLIENT_ID", "GOOGLE_CLIENT_SECRET"] },
  // Fake mode: its own encryption key, and the fake client pair (the Worker uses the fake constants anyway), so
  // neither the production key nor the real Google client can reach it.
  "gws-mcp-e2e": {
    config: CONFIGS.e2e.local,
    names: ["TOKEN_ENC_KEY", "GOOGLE_CLIENT_ID", "GOOGLE_CLIENT_SECRET"],
    sources: {
      TOKEN_ENC_KEY: { envKey: "E2E_TOKEN_ENC_KEY" },
      GOOGLE_CLIENT_ID: { fixed: FAKE_CLIENT_ID },
      GOOGLE_CLIENT_SECRET: { fixed: FAKE_CLIENT_SECRET },
    },
  },
  "gws-mcp-fake-google": {
    config: CONFIGS.fake.local,
    names: ["FAKE_ADMIN_TOKEN", "FAKE_SIGNING_KEY", "FAKE_LOGIN_SECRET"],
  },
};

/** Env keys owned by this deployment, generated when absent. Anything else (the Google client) must be provided. */
const GENERATED = new Set(["TOKEN_ENC_KEY", "E2E_TOKEN_ENC_KEY", "FAKE_ADMIN_TOKEN", "FAKE_SIGNING_KEY", "FAKE_LOGIN_SECRET"]);

/** Secret names whose deployed value must not be replaced unless `--rotate` is passed: stored data depends on them. */
const ROTATE_ONLY = new Set(["TOKEN_ENC_KEY"]);

const STDERR_TAIL_LINES = 20;

export type SpawnLike = (
  cmd: string,
  args: readonly string[],
  opts: SpawnOptions & { env?: NodeJS.ProcessEnv },
) => Pick<ChildProcess, "stdin" | "stdout" | "stderr" | "on">;

export interface PutSecretsOptions {
  worker: string;
  names: readonly string[];
  envFile: string;
  spawn?: SpawnLike;
  log?: (line: string) => void;
  /** Replaces each requested ROTATE_ONLY secret with a freshly generated value, in the env file and deployed. */
  rotate?: boolean;
}

export function generateKey(): string {
  return Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString("base64");
}

/** A `KEY=value` line, optionally `export`-prefixed. */
const ENV_LINE = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/;

/** First non-empty value per wanted key, as the E2E harness reads the same file. An `export ` prefix and quotes are stripped. */
function readValues(file: string, names: readonly string[]): Map<string, string> {
  const out = new Map<string, string>();
  if (!existsSync(file)) return out;
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = ENV_LINE.exec(line);
    const key = m?.[1];
    if (!key || !names.includes(key) || out.has(key)) continue;
    const value = (m[2] ?? "").replace(/^(['"])(.*)\1$/, "$2");
    if (value !== "") out.set(key, value);
  }
  return out;
}

/** Appends `KEY=value` lines; creates the file if needed. Mode 600 either way. Earlier lines stay untouched. */
function appendValues(file: string, entries: ReadonlyArray<[string, string]>): void {
  const text = entries.map(([k, v]) => `${k}=${v}\n`).join("");
  if (existsSync(file)) {
    const current = readFileSync(file, "utf8");
    appendFileSync(file, current === "" || current.endsWith("\n") ? text : `\n${text}`);
  } else {
    writeFileSync(file, text, { mode: 0o600 });
  }
  chmodSync(file, 0o600);
}

/**
 * Sets each key to its new value: the key's first line becomes `KEY=value` and its later lines are dropped;
 * absent keys are appended. Every other line is kept byte for byte. Written through a sibling temp file and a
 * rename, so a failed write cannot truncate the env file. Mode 600.
 */
function replaceValues(file: string, entries: ReadonlyArray<[string, string]>): void {
  const wanted = new Map(entries);
  const written = new Set<string>();
  const kept: string[] = [];
  for (const line of existsSync(file) ? readFileSync(file, "utf8").split("\n") : []) {
    const key = ENV_LINE.exec(line)?.[1];
    if (key === undefined || !wanted.has(key)) {
      kept.push(line);
    } else if (!written.has(key)) {
      kept.push(`${key}=${wanted.get(key)}`);
      written.add(key);
    }
  }
  let text = kept.join("\n");
  const absent = entries.filter(([k]) => !written.has(k));
  if (absent.length > 0) {
    text += `${text === "" || text.endsWith("\n") ? "" : "\n"}${absent.map(([k, v]) => `${k}=${v}\n`).join("")}`;
  }
  const tmp = `${file}.${process.pid}.tmp`;
  try {
    writeFileSync(tmp, text, { mode: 0o600 });
    chmodSync(tmp, 0o600);
    renameSync(tmp, file);
  } catch (e) {
    rmSync(tmp, { force: true });
    throw e;
  }
}

export function scrub(text: string, values: Iterable<string>): string {
  let out = text;
  for (const v of values) if (v.length > 0) out = out.split(v).join("[REDACTED]");
  return out;
}

/** The secret names in `wrangler secret list --format json` output, or null when it is not that list. */
export function secretNames(stdout: string): Set<string> | null {
  const start = stdout.indexOf("[");
  if (start < 0) return null;
  try {
    const parsed: unknown = JSON.parse(stdout.slice(start));
    if (!Array.isArray(parsed)) return null;
    const names = new Set<string>();
    for (const item of parsed) {
      const name: unknown = typeof item === "object" && item !== null ? (item as { name?: unknown }).name : undefined;
      if (typeof name !== "string") return null;
      names.add(name);
    }
    return names;
  } catch {
    return null;
  }
}

/** Runs `npx wrangler <args>` in the repository root with `value` on stdin (never in argv). */
export function runWrangler(spawn: SpawnLike, args: readonly string[], value: string): Promise<{ code: number; stdout: string; stderr: string }> {
  return new Promise((resolve) => {
    let stdout = "";
    let stderr = "";
    let settled = false;
    const done = (code: number) => {
      if (settled) return;
      settled = true;
      resolve({ code, stdout, stderr });
    };
    const child = spawn("npx", ["wrangler", ...args], { cwd: ROOT, stdio: ["pipe", "pipe", "pipe"], env: process.env, shell: false });
    child.stdout?.on("data", (d: Buffer) => {
      stdout = (stdout + d.toString("utf8")).slice(-256_000);
    });
    child.stderr?.on("data", (d: Buffer) => {
      stderr = (stderr + d.toString("utf8")).slice(-16_000);
    });
    child.on("error", (e: Error) => {
      stderr += `\n${e.message}`;
      done(-1);
    });
    child.on("close", (code: number | null) => done(code ?? -1));
    // A child that exits early closes stdin; the close event reports the failure.
    child.stdin?.on("error", () => {});
    child.stdin?.end(value);
  });
}

/**
 * Returns the process exit code: 0 ok, 1 a wrangler failure, 2 a refusal (a required value missing, or a deployed
 * ROTATE_ONLY secret without `rotate`), 64 a usage error.
 */
export async function putSecrets(opts: PutSecretsOptions): Promise<{ exitCode: number }> {
  const log = opts.log ?? ((line: string) => console.log(line));
  const spawn = opts.spawn ?? (nodeSpawn as unknown as SpawnLike);
  const target = Object.hasOwn(WORKERS, opts.worker) ? WORKERS[opts.worker] : undefined;
  if (!target) {
    log(`usage: unknown worker "${opts.worker}"; allowed: ${Object.keys(WORKERS).join(", ")}`);
    return { exitCode: 64 };
  }
  const names = [...new Set(opts.names)];
  const foreign = names.filter((n) => !target.names.includes(n));
  if (names.length === 0 || foreign.length > 0) {
    log(`usage: --names must be a non-empty subset of ${target.names.join(", ")}${foreign.length ? ` (got ${foreign.join(", ")})` : ""}`);
    return { exitCode: 64 };
  }

  // Secret name -> env key for the names read from the env file; fixed values never read it.
  const envKeyOf = new Map<string, string>();
  const fixed = new Map<string, string>();
  for (const n of names) {
    const source: Source = target.sources?.[n] ?? { envKey: n };
    if ("fixed" in source) fixed.set(n, source.fixed);
    else envKeyOf.set(n, source.envKey);
  }
  /** Values by env key. */
  const values = readValues(opts.envFile, [...envKeyOf.values()]);
  const blocked = [...envKeyOf.values()].filter((k) => !values.has(k) && !GENERATED.has(k));
  if (blocked.length > 0) {
    for (const k of blocked) log(`BLOCKED: ${k} is missing in ${path.basename(opts.envFile)}; it is provided by the operator and never generated`);
    return { exitCode: 2 };
  }

  const config = path.join(ROOT, target.config);
  const logTail = (stderr: string) => {
    const tail = scrub(stderr, [...values.values(), ...fixed.values()]).trimEnd().split("\n").slice(-STDERR_TAIL_LINES);
    for (const line of tail) if (line.trim() !== "") log(`  ${line}`);
  };

  // Checked before anything is generated, written or uploaded. Names only: wrangler never returns values.
  const guarded = names.filter((n) => ROTATE_ONLY.has(n));
  if (guarded.length > 0 && !opts.rotate) {
    const listed = await runWrangler(spawn, ["secret", "list", "--name", opts.worker, "--config", config, "--format", "json"], "");
    const deployed = listed.code === 0 ? secretNames(listed.stdout) : null;
    if (!deployed) {
      log(`REFUSED: could not list the secrets of ${opts.worker} (exit ${listed.code}), so ${guarded.join(", ")} may already be deployed`);
      logTail(listed.stderr);
      return { exitCode: 1 };
    }
    const present = guarded.filter((n) => deployed.has(n));
    if (present.length > 0) {
      for (const n of present) {
        log(`REFUSED: ${n} is already set on ${opts.worker}; replacing it makes every stored Google token unreadable. Pass --rotate to replace it on purpose`);
      }
      return { exitCode: 2 };
    }
  }

  // Rotation and generation work on env keys: a rotate-only secret is rewritten under the key it is read from.
  const rotated: Array<[string, string]> = opts.rotate
    ? guarded.flatMap((n) => {
        const k = envKeyOf.get(n);
        return k === undefined ? [] : [[k, generateKey()] as [string, string]];
      })
    : [];
  if (rotated.length > 0) replaceValues(opts.envFile, rotated);
  const fresh: Array<[string, string]> = [...envKeyOf.values()]
    .filter((k) => !values.has(k) && !rotated.some(([r]) => r === k))
    .map((k) => [k, generateKey()]);
  if (fresh.length > 0) appendValues(opts.envFile, fresh);
  for (const [k, v] of [...rotated, ...fresh]) values.set(k, v);
  for (const n of names) {
    const k = envKeyOf.get(n);
    if (k === undefined) {
      log(`fixed ${n} (fake placeholder, not read from ${path.basename(opts.envFile)})`);
      continue;
    }
    const state = rotated.some(([r]) => r === k) ? "rotated" : fresh.some(([f]) => f === k) ? "generated" : "present";
    log(k === n ? `env ${n} ${state}` : `env ${k} ${state} (for ${n})`);
  }

  for (const n of names) {
    const k = envKeyOf.get(n);
    const value = (k === undefined ? fixed.get(n) : values.get(k)) ?? "";
    const { code, stderr } = await runWrangler(spawn, ["secret", "put", n, "--name", opts.worker, "--config", config], value);
    if (code !== 0) {
      log(`secret ${n} FAILED on ${opts.worker} (exit ${code})`);
      logTail(stderr);
      return { exitCode: 1 };
    }
    log(`secret ${n} set on ${opts.worker}`);
  }
  return { exitCode: 0 };
}

function arg(argv: readonly string[], name: string): string | undefined {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : undefined;
}

async function main(): Promise<void> {
  const argv = process.argv.slice(2);
  const worker = arg(argv, "--worker") ?? "";
  const names = (arg(argv, "--names") ?? "").split(",").map((s) => s.trim()).filter(Boolean);
  const envFile = path.resolve(arg(argv, "--env-file") ?? path.join(ROOT, ".env"));
  const { exitCode } = await putSecrets({ worker, names, envFile, rotate: argv.includes("--rotate") });
  process.exitCode = exitCode;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e: unknown) => {
    // Only the error class: a message could in theory quote file content.
    console.error(`put-secrets: failed (${e instanceof Error ? e.name : "unknown error"})`);
    process.exitCode = 1;
  });
}
