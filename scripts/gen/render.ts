import type { EmittedService, GenMethod } from "./service";
import { lit } from "./zod-emit";

/** Generated modules import only zod and contract types; the helpers below are identical in every service file. */
const RUNTIME = `function memo<T>(make: () => T): () => T {
  let value: T | undefined;
  return () => (value ??= make());
}

function declsFor(refs: readonly SchemaName[]): string {
  const seen = new Set<SchemaName>();
  const visit = (name: SchemaName): void => {
    if (seen.has(name)) return;
    seen.add(name);
    for (const dep of types[name][1]) visit(dep);
  };
  for (const ref of refs) visit(ref);
  return [...seen]
    .sort()
    .map((name) => types[name][0])
    .join("\\n");
}

interface Def {
  name: string;
  effect: FnDef["effect"];
  description: string;
  signature: string;
  example: string;
  tags: string[];
  method: MethodMeta;
  input: () => z.ZodType;
  output: () => z.ZodType;
  tsHead: string;
  refs: SchemaName[];
}

// Schemas and declarations are built on first use, so importing this module stays cheap.
function fn(d: Def): FnDef {
  const input = memo(d.input);
  const output = memo(d.output);
  const tsDecl = memo(() => [d.tsHead, declsFor(d.refs)].filter((part) => part.length > 0).join("\\n"));
  return {
    kind: "google",
    name: d.name,
    service: SERVICE,
    effect: d.effect,
    description: d.description,
    signature: d.signature,
    example: d.example,
    tags: d.tags,
    scopes: d.method.scopes,
    method: d.method,
    get tsDecl() {
      return tsDecl();
    },
    get input() {
      return input();
    },
    get output() {
      return output();
    },
  };
}
`;

const HEADER = (file: string, revision: string): string =>
  `// @generated by scripts/gen-sdk.ts from ${file} (revision ${revision}). Do not edit.\n`;

const list = (values: readonly string[]): string => `[${values.map(lit).join(", ")}]`;

function renderMethod(m: GenMethod): string {
  const { meta } = m;
  const metaJson = JSON.stringify({
    id: meta.id,
    service: meta.service,
    httpMethod: meta.httpMethod,
    rootUrl: meta.rootUrl,
    servicePath: meta.servicePath,
    path: meta.path,
    pathParams: meta.pathParams,
    queryParams: meta.queryParams,
    requestBody: meta.requestBody,
    ...(meta.mediaUpload !== undefined ? { mediaUpload: meta.mediaUpload } : {}),
    mediaDownload: meta.mediaDownload,
    scopes: meta.scopes,
    effect: meta.effect,
  });
  return [
    "  fn({",
    `    name: ${lit(m.id)},`,
    `    effect: ${lit(meta.effect)},`,
    `    description: ${lit(m.description)},`,
    `    signature: ${lit(m.signature)},`,
    `    example: ${lit(m.example)},`,
    `    tags: ${list(m.tags)},`,
    `    method: ${metaJson},`,
    `    input: () => ${m.inputExpr},`,
    `    output: () => ${m.outputExpr},`,
    `    tsHead: ${lit(m.tsHead)},`,
    `    refs: ${list(m.refs)},`,
    "  }),",
  ].join("\n");
}

/** One generated module per service: lazy schema factories plus the registered functions. */
export function renderService(e: EmittedService): string {
  const names = [...e.schemas.keys()];
  const schemaLines = names.map((n) => `  ${lit(n)}: memo(() => ${e.schemas.get(n)!.expr}),`);
  const typeLines = names.map((n) => {
    const s = e.schemas.get(n)!;
    return `  ${lit(n)}: [${lit(s.ts)}, ${list(s.deps)}],`;
  });
  const union = names.length === 0 ? "never" : names.map(lit).join(" | ");
  return [
    HEADER(`discovery/${e.api}.${e.version}.json`, e.revision),
    'import { z } from "zod";',
    'import type { FnDef, MethodMeta } from "../../contracts";',
    "",
    `const SERVICE = ${lit(e.service)};`,
    `type SchemaName = ${union};`,
    "",
    "const schemas: Record<SchemaName, () => z.ZodType> = {",
    ...schemaLines,
    "};",
    "",
    "const types: Record<SchemaName, readonly [decl: string, deps: readonly SchemaName[]]> = {",
    ...typeLines,
    "};",
    "",
    RUNTIME,
    `export const ${e.api}Fns: FnDef[] = [`,
    ...e.methods.map(renderMethod),
    "];",
    "",
  ].join("\n");
}
