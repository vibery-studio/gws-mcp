import { createHash } from "node:crypto";
import type { GoogleService } from "../../src/config";
import { renderService } from "./render";
import { API_NAMES, GENERATED_APIS, emitService, type ApiName, type ApiSpec, type MethodAllowlist } from "./service";
import type { DiscoveryDoc, Unsupported } from "./types";
import { byteOrder, lit } from "./zod-emit";

export interface ServiceInput {
  doc: DiscoveryDoc;
  version: string;
  revision: string;
}

/** One pinned document per api name (see `GENERATED_APIS`). */
export type GenerateInput = Partial<Record<ApiName, ServiceInput>>;

export interface ServiceTotals {
  supported: number;
  unsupported: number;
  total: number;
}

export interface GenerateResult {
  /** Path relative to `src/sdk/generated`, in byte order. */
  files: Map<string, string>;
  hash: string;
  unsupported: Array<Unsupported & { service: GoogleService }>;
  droppedUploads: string[];
  /** Per api, in output order. */
  totals: Partial<Record<ApiName, ServiceTotals>>;
  supported: number;
  total: number;
}

const BANNER = "// @generated by scripts/gen-sdk.ts. Do not edit.";

/** `sha256:<hex>` over each file as path, NUL, bytes, in byte order of path. The manifest is excluded. */
export function hashFiles(files: ReadonlyMap<string, string>): string {
  const h = createHash("sha256");
  for (const path of [...files.keys()].filter((p) => p !== "manifest.ts").sort(byteOrder)) {
    h.update(path);
    h.update("\0");
    h.update(files.get(path)!, "utf8");
  }
  return `sha256:${h.digest("hex")}`;
}

function describeAllowlist(allow: MethodAllowlist): string {
  const parts = [
    ...(allow.idPrefixes ?? []).map((p) => `\`${p}*\``),
    ...(allow.ids ?? []).map((p) => `\`${p}\``),
    ...(allow.idSuffixes ?? []).map((p) => `\`*${p}\``),
  ];
  return parts.join(", ");
}

function renderReport(
  unsupported: ReadonlyArray<Unsupported>,
  totals: GenerateResult["totals"],
  supported: number,
  total: number,
): string {
  const rows = unsupported.map((u) => `| ${u.method} | ${u.reason.replace(/\|/g, "\\|")} |`);
  const perService = API_NAMES.flatMap((s) => {
    const t = totals[s];
    return t === undefined ? [] : [`- ${s}: ${t.supported} supported, ${t.unsupported} unsupported, ${t.total} total`];
  });
  const allowlists = API_NAMES.flatMap((s) => {
    const spec: ApiSpec = GENERATED_APIS[s];
    return totals[s] !== undefined && spec.allow !== undefined ? [`- ${s}: ${describeAllowlist(spec.allow)}`] : [];
  });
  return [
    "# Unsupported methods",
    "",
    "Discovery methods that are not generated, with the reason. Produced by scripts/gen-sdk.ts. Do not edit.",
    "",
    ...(allowlists.length === 0
      ? []
      : [
          "Only these methods are considered for the apis below. Every other method of those documents is omitted by the allowlist and counted in no total.",
          "",
          ...allowlists,
          "",
        ]),
    "| method | reason |",
    "|---|---|",
    ...rows,
    "",
    "## Totals",
    "",
    ...perService,
    `- all: ${supported} supported, ${total - supported} unsupported, ${total} total`,
    "",
  ].join("\n");
}

/** Generates every output file in memory. Pure: the same input always yields the same bytes and hash. */
export function generate(input: GenerateInput): GenerateResult {
  const files = new Map<string, string>();
  const unsupported: GenerateResult["unsupported"] = [];
  const droppedUploads: string[] = [];
  const totals: GenerateResult["totals"] = {};
  const services = API_NAMES.filter((s) => input[s] !== undefined);
  const versions: Record<string, string> = {};
  let supported = 0;
  let total = 0;

  const rendered = new Map<string, string>();
  for (const service of services) {
    const { doc, version, revision } = input[service]!;
    const spec: ApiSpec = GENERATED_APIS[service];
    const emitted = emitService(spec.service, { ...doc, version, revision }, { api: service, ...(spec.allow !== undefined ? { allow: spec.allow } : {}) });
    rendered.set(`${service}.ts`, renderService(emitted));
    for (const u of emitted.unsupported) unsupported.push({ ...u, service: spec.service });
    droppedUploads.push(...emitted.droppedUploads);
    totals[service] = {
      supported: emitted.methods.length,
      unsupported: emitted.unsupported.length,
      total: emitted.total,
    };
    supported += emitted.methods.length;
    total += emitted.total;
    versions[service] = `${version}@${revision}`;
  }
  unsupported.sort((a, b) => byteOrder(a.method, b.method));
  droppedUploads.sort(byteOrder);

  const index = [
    BANNER,
    'import type { FnDef } from "../../contracts";',
    ...services.map((s) => `import { ${s}Fns } from "./${s}";`),
    "",
    "/** Every function generated from the pinned Discovery documents, in service order. */",
    `export const generatedFns: FnDef[] = [${services.map((s) => `...${s}Fns`).join(", ")}];`,
    "",
  ].join("\n");

  const all = new Map<string, string>([...rendered, ["index.ts", index], ["UNSUPPORTED.md", renderReport(unsupported, totals, supported, total)]]);
  const hash = hashFiles(all);
  const manifest = [
    BANNER,
    "export const sdkManifest = {",
    `  hash: ${lit(hash)},`,
    "  discovery: {",
    ...services.map((s) => `    ${s}: ${lit(versions[s]!)},`),
    "  },",
    `  methods: { supported: ${supported}, total: ${total} },`,
    "};",
    "",
  ].join("\n");
  all.set("manifest.ts", manifest);

  for (const path of [...all.keys()].sort(byteOrder)) files.set(path, all.get(path)!);
  return { files, hash, unsupported, droppedUploads, totals, supported, total };
}
